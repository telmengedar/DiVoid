using Backend.Models.Auth;
using Backend.Models.Messages;
using Backend.Models.Users;
using Backend.Services.MessageChanges;
using Npgsql;
using Pooshit.Ocelot.Clients;
using Pooshit.Ocelot.Entities;
using Pooshit.Ocelot.Info;
using Pooshit.Ocelot.Schemas;

namespace Backend.tests.Fixtures;

internal sealed class InboxPostgresOwnerFixture : IAsyncDisposable {
    readonly string admin;
    readonly string role = "inbox_owner_" + Guid.NewGuid().ToString("N");
    readonly string deniedRole = "inbox_denied_" + Guid.NewGuid().ToString("N");
    readonly string schema = "inbox_schema_" + Guid.NewGuid().ToString("N");

    internal InboxPostgresOwnerFixture() {
        admin = Environment.GetEnvironmentVariable("POSTGRES_CONNECTION")!;
        if (string.IsNullOrEmpty(admin))
            Assert.Ignore("POSTGRES_CONNECTION is required for private PostgreSQL role qualification.");
    }

    internal string Schema => schema;

    internal IEntityManager Entities { get; private set; } = null!;

    internal IEntityManager DeniedEntities { get; private set; } = null!;

    internal async Task StartAsync(string? copySchema = null) {
        using NpgsqlCommandBuilder identifiers = new();
        await ExecuteAdmin($"CREATE ROLE {identifiers.QuoteIdentifier(role)} LOGIN; CREATE ROLE {identifiers.QuoteIdentifier(deniedRole)} LOGIN; CREATE SCHEMA {identifiers.QuoteIdentifier(schema)} AUTHORIZATION {identifiers.QuoteIdentifier(role)};");
        if (copySchema != null)
            await ExecuteAdmin($"GRANT USAGE ON SCHEMA {identifiers.QuoteIdentifier(copySchema)} TO {identifiers.QuoteIdentifier(role)}; GRANT SELECT ON ALL TABLES IN SCHEMA {identifiers.QuoteIdentifier(copySchema)} TO {identifiers.QuoteIdentifier(role)};");
        Entities = CreateEntities(role);
        DeniedEntities = CreateEntities(deniedRole);
        SchemaService schemas = new(Entities.DBClient);
        using (Transaction transaction = Entities.Transaction()) {
            await MessageChangeSchema.LockAsync(Entities, transaction);
            if (copySchema == null) {
                await schemas.CreateOrUpdateSchema<User>(transaction);
                await schemas.CreateOrUpdateSchema<ApiKey>(transaction);
                await schemas.CreateOrUpdateSchema<Message>(transaction);
            } else {
                foreach (string table in new[] { "divoid_user", "apikey", "message" }) {
                    string target = identifiers.QuoteIdentifier(schema) + "." + identifiers.QuoteIdentifier(table);
                    string original = identifiers.QuoteIdentifier(copySchema) + "." + identifiers.QuoteIdentifier(table);
                    await using NpgsqlCommand command = new($"CREATE TABLE {target} (LIKE {original} INCLUDING CONSTRAINTS); ALTER TABLE {target} ADD PRIMARY KEY(id); ALTER TABLE {target} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;", (NpgsqlConnection)transaction.DbTransaction.Connection, (NpgsqlTransaction)transaction.DbTransaction);
                    await command.ExecuteNonQueryAsync();
                    Assert.That(await Shape((NpgsqlConnection)transaction.DbTransaction.Connection, (NpgsqlTransaction)transaction.DbTransaction, target), Is.EqualTo(await Shape((NpgsqlConnection)transaction.DbTransaction.Connection, (NpgsqlTransaction)transaction.DbTransaction, original)));
                }
            }
            await MessageChangeSchema.InstallAsync(Entities, transaction);
            transaction.Commit();
        }
        await ExecuteAdmin($"GRANT USAGE ON SCHEMA {identifiers.QuoteIdentifier(schema)} TO {identifiers.QuoteIdentifier(deniedRole)}; GRANT SELECT ON ALL TABLES IN SCHEMA {identifiers.QuoteIdentifier(schema)} TO {identifiers.QuoteIdentifier(deniedRole)};");
    }

    static async Task<string[]> Shape(NpgsqlConnection connection, NpgsqlTransaction transaction, string table) {
        await using NpgsqlCommand command = new("SELECT a.attname,format_type(a.atttypid,a.atttypmod),a.attnotnull,CASE WHEN a.attname='id' THEN 'local-generator' ELSE COALESCE(pg_get_expr(d.adbin,d.adrelid),'') END FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum WHERE a.attrelid=@table::regclass AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum", connection, transaction);
        command.Parameters.AddWithValue("table", table);
        List<string> columns = [];
        await using NpgsqlDataReader reader = await command.ExecuteReaderAsync();
        while (await reader.ReadAsync())
            columns.Add(reader.GetString(0) + "|" + reader.GetString(1) + "|" + reader.GetBoolean(2) + "|" + reader.GetString(3));
        return columns.ToArray();
    }

    IEntityManager CreateEntities(string actor) {
        string connection = new NpgsqlConnectionStringBuilder(admin) { Username = actor, Password = "", SearchPath = schema, Pooling = false }.ConnectionString;
        return new EntityManager(ClientFactory.Create(() => new NpgsqlConnection(connection), new PostgreInfo(), true));
    }

    async Task ExecuteAdmin(string sql) {
        await using NpgsqlConnection connection = new(admin);
        await connection.OpenAsync();
        await using NpgsqlCommand command = new(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    /// <inheritdoc />
    public async ValueTask DisposeAsync() {
        using NpgsqlCommandBuilder identifiers = new();
        await ExecuteAdmin($"DROP OWNED BY {new NpgsqlCommandBuilder().QuoteIdentifier(deniedRole)}; DROP OWNED BY {new NpgsqlCommandBuilder().QuoteIdentifier(role)}; DROP SCHEMA IF EXISTS {identifiers.QuoteIdentifier(schema)} CASCADE; DROP OWNED BY {identifiers.QuoteIdentifier(deniedRole)}; DROP OWNED BY {identifiers.QuoteIdentifier(role)}; DROP ROLE IF EXISTS {identifiers.QuoteIdentifier(deniedRole)}; DROP ROLE IF EXISTS {identifiers.QuoteIdentifier(role)};");
    }
}
